export function Icon({ name, ...props }: { name: string } & LucideProps) {
  const C = ICONS[name] ?? BookOpen;
  return <C aria-hidden {...props} />;
}

export const hasIcon = (name: string) => name in ICONS;

export const AVATARS: { id: string; icon: LucideIcon; label: string }[] = [
  { id: 'rocket', icon: Rocket, label: 'Rocket' },
  { id: 'store', icon: Store, label: 'Storefront' },
  { id: 'truck', icon: Truck, label: 'Truck' },
  { id: 'lightbulb', icon: Lightbulb, label: 'Light bulb' },
  { id: 'gem', icon: Gem, label: 'Gem' },
  { id: 'crown', icon: Crown, label: 'Crown' },
  { id: 'flame', icon: Flame, label: 'Flame' },
  { id: 'shirt', icon: Shirt, label: 'T-shirt' },
];

export function avatarIcon(id: string): LucideIcon {
  return AVATARS.find((a) => a.id === id)?.icon ?? Rocket;
}
